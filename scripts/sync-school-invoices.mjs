import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'gallery/designs/assets/school-invoices');
const data = JSON.parse(fs.readFileSync(path.join(dir, 'data.json'), 'utf8'));
const js = `// Generated by scripts/sync-school-invoices.mjs; edit data.json instead.\nwindow.SCHOOL_INVOICE_DATA = ${JSON.stringify(data, null, 2)};\n`;
const file = path.join(dir, 'data.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(file, 'utf8') !== js) throw new Error('School invoice data.js is stale');
} else fs.writeFileSync(file, js);
